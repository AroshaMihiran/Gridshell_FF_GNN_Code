function report=st_export_design(design,base,material,checks,loadInfo,symmetry,folder)
if ~isfolder(folder),mkdir(folder);end
ev=design.final;nn=size(base.originalNodes,1);nm=size(base.originalBars,1);nc=numel(ev.cases);
model=ev.model;fields={'nodes','bars','E','G','A','I2','I3','J','As2','As3','restraints','originalNodes', ...
    'originalBars','originalMemberLengths','frameMemberRows','frameSegments','nodeIds','memberIds'};
exportModel=struct();for f=fields,exportModel.(f{1})=model.(f{1});end
exportModel.sides=ev.sides;exportModel.groups=design.groups;exportModel.material=material;exportModel.designOptions=checks;
exportModel.initialStressTransferred=false;gs_write_json(fullfile(folder,'frame_model.json'),exportModel);
caseReports=cell(nc,1);caseData=cell(nc,1);ulsUZ=zeros(nn,nc);
for c=1:nc
    s=ev.cases{c};def=ev.caseDefinitions(c);caseData{c}=s;
    caseReports{c}=struct('name',s.name,'gammaG',def.gammaG,'gammaW',def.gammaW,'windSign',def.windSign,'kmod',def.kmod, ...
        'maximumUtilization',max(ev.caseMemberRatios(:,c)),'maximumAbsUZ_m',s.maximumAbsUZ, ...
        'maximumTranslation_m',s.maximumTranslation,'residual_kN',s.residualNorm,'residualTolerance_kN',s.residualTolerance, ...
        'globalForceClosure_kN',s.globalForceClosure,'globalMomentClosure_kNm',s.globalMomentClosure, ...
        'totalAppliedVertical_kN',sum(s.appliedNodalForces(:,3)),'tensionMembers',sum(ev.memberNmax(:,c)>1e-8), ...
        'compressionMembers',sum(ev.memberNmin(:,c)<-1e-8),'minN_kN',min(ev.memberNmin(:,c)),'maxN_kN',max(ev.memberNmax(:,c))); %#ok<AGROW>
    ulsUZ(:,c)=s.displacements(1:nn,3);
    writetable(array2table([base.memberIds,ev.caseMemberRatios(:,c),ev.memberNmin(:,c),ev.memberNmax(:,c),ev.memberM2(:,c),ev.memberM3(:,c)], ...
        'VariableNames',{'Member_ID','Utilization','Nmin_kN','Nmax_kN','M2max_kNm','M3max_kNm'}),fullfile(folder,[s.name '_members.csv']));
end
caseReports=vertcat(caseReports{:});
% Characteristic instantaneous and final (creep) displacement estimates.
% One leading wind action: psi2=0, SC2 kdef=.8; retain signed fields.
uG=ev.cases{1}.displacements/1.35;uW=(ev.cases{2}.displacements-ev.cases{1}.displacements)/1.5;
service=struct('complianceAssessed',false,'displacementLimitSpecified',false,'kdef',material.kdef,'psi2Wind',0, ...
    'instantaneousReference',uG+uW,'instantaneousReversed',uG-uW, ...
    'finalReference',(1+material.kdef)*uG+uW,'finalReversed',(1+material.kdef)*uG-uW);
for name={'instantaneousReference','instantaneousReversed','finalReference','finalReversed'}
    field=name{1};service.([field 'MaximumAbsUZ_m'])=max(abs(service.(field)(:,3)));
end
gs_write_json(fullfile(folder,'frame_cases.json'),caseData);
gs_write_json(fullfile(folder,'case_reports.json'),caseReports);
gs_write_json(fullfile(folder,'serviceability_displacements.json'),service);
gs_write_json(fullfile(folder,'load_components.json'),loadInfo);gs_write_json(fullfile(folder,'symmetry_groups.json'),symmetry);
nodeTable=array2table([base.nodeIds,base.originalNodes,max(abs(ulsUZ),[],2)], ...
    'VariableNames',{'Node_ID','X_m','Y_m','Z_m','MaximumAbsULS_UZ_m'});
writetable(nodeTable,fullfile(folder,'design_nodes.csv'));
memberTable=array2table([base.memberIds,base.originalBars,design.groups,ev.sides,ev.section.A,base.originalMemberLengths, ...
    ev.memberRatios,ev.governingCase,min(ev.memberNmin,[],2),max(ev.memberNmax,[],2),max(ev.memberM2,[],2),max(ev.memberM3,[],2)], ...
    'VariableNames',{'Member_ID','Node1_Row','Node2_Row','Group','Side_m','Area_m2','Length_m','Utilization','GoverningCase', ...
    'EnvelopeNmin_kN','EnvelopeNmax_kN','EnvelopeM2_kNm','EnvelopeM3_kNm'});
memberTable.GoverningMode=ev.governingMode;writetable(memberTable,fullfile(folder,'design_members.csv'));
writetable(array2table(design.history,'VariableNames',{'Iteration','MaximumUtilization','Volume_m3','MaximumAbsULS_UZ_m', ...
    'ProposedRelativeSideChange','TimberSelfWeight_kN','Elapsed_s'}),fullfile(folder,'sizing_history.csv'));
writematrix(design.sizeHistory,fullfile(folder,'side_history_m.csv'));
report=struct('success',design.success,'reason',design.reason,'nodeCount',nn,'physicalMemberCount',nm,'numericalElementCount',size(base.bars,1), ...
    'maximumUtilization',ev.maxRatio,'minimumUtilization',min(ev.memberRatios),'initialMaximumUtilization',design.initial.maxRatio, ...
    'volume_m3',ev.volume,'initialVolume_m3',design.initial.volume,'minimumSide_m',min(ev.sides),'maximumSide_m',max(ev.sides), ...
    'timberSelfWeight_kN',ev.unfactoredTimberSelfWeight_kN,'maximumAbsULS_UZ_m',ev.maxAbsUZ,'maximumMomentEnvelope_kNm',ev.maxMoment, ...
    'iterations',size(design.history,1),'seconds',design.seconds,'symmetryGroups',symmetry.numberOfGroups, ...
    'geometryFixedDuringSizing',true,'fftCallsDuringSizing',0,'allPhysicalMembersRetained',true, ...
    'material',material,'options',design.options,'cases',caseReports,'fullDesignVerified',false, ...
    'effectiveLengthAssumption','K2=K3=1 over each physical joint-to-joint member; local braced-end assumption, not justified by rigid joints alone', ...
    'interactionEnvelope','Exact extrema of axial and bending actions per numerical segment conservatively combined within each case; cases are never mixed within one interaction', ...
    'excludedChecks',{{'global and second-order stability','lateral-torsional buckling','shear and torsion resistance','connections','net-section/detailing','serviceability limit compliance'}}, ...
    'optimizationClaim','Feasible grouped iterative sizing; neither all utilizations equal to one nor a global minimum is claimed');
gs_write_json(fullfile(folder,'summary.json'),report);
end
