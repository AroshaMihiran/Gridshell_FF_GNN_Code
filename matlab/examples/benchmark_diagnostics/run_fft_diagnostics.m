function report=run_fft_diagnostics
% Isolated repeat of the upward-wind benchmark, with passive traces.
root=fileparts(mfilename('fullpath'));addpath(fullfile(root,'code'));
out=fullfile(root,'..','..','outputs','benchmark_diagnostics');if ~isfolder(out),mkdir(out);end
o=struct('WindDirection','upward','ElasticModulusFactor',.84, ...
    'DeadLoadFactor',1,'WindLoadFactor',1,'MakePlots',false, ...
    'FailOnNonconvergence',false,'IntegrationOrder',8);
r=gs_fft_analysis(fullfile(root,'inputs'),o);
assert(r.success,'Instrumented benchmark did not meet the unchanged criteria.');
s=r.state;m=r.model;
assert(size(m.nodes,1)==64&&size(m.bars,1)==112&&numel(m.panels)==49);
assert(sum(m.fixedNodes)==16&&all(m.q1==4.5)&&all(m.q2==.5));
save(fullfile(out,'instrumented_fft.mat'),'r','-v7');
save(fullfile(out,'fft_result.mat'),'r','-v7');
gs_write_json(fullfile(out,'outer_history.json'),s.history);
gs_write_json(fullfile(out,'inner_history.json'),s.innerHistory);
writetable(struct2table(s.history),fullfile(out,'outer_history.csv'));
inner=[];
for k=1:numel(s.innerHistory)
    t=struct2table(s.innerHistory{k});
    writetable(t,fullfile(out,sprintf('inner_history_%02d.csv',k)));
    inner=[inner;t]; %#ok<AGROW>
end
writetable(inner,fullfile(out,'inner_history_all.csv'));
roof=s.nodes;roof(:,3)=-roof(:,3);
restraints=reshape(ismember((1:3*size(m.nodes,1))',m.fixedDofs),3,[])';
h=struct('success',true,'nodes',s.nodes,'roofNodes',roof,'referenceNodes',m.nodes, ...
    'bars',m.bars,'A',m.A,'nodeIds',m.nodeIds,'memberIds',m.memberIds, ...
    'translationalRestraints',restraints,'allFinalForces',reshape(s.F,3,[])', ...
    'signedAxialForce',s.force,'E_effective',s.E,'Lref',s.Lref, ...
    'qD',m.q1,'qW',m.q2,'panels',{m.panels},'panelIds',m.panelIds,'E_input',m.E, ...
    'windDirection','upward','windSign',1,'deadSign',-1, ...
    'residualCheck',r.residualCheck,'quadratureCheck',r.quadratureCheck, ...
    'designFactorsUsedInFFT',false,'initialStressTransferred',false,'mirroredExactlyOnce',true);
gs_write_json(fullfile(out,'handoff.json'),h);
report=struct('success',r.success,'nodeCount',size(m.nodes,1), ...
    'memberCount',size(m.bars,1),'panelCount',numel(m.panels), ...
    'supportCount',sum(m.fixedNodes),'outerIterations',s.iterations, ...
    'innerIterations',[s.history.innerIterations], ...
    'relativeDisplacement',s.relativeDisplacement,'residualCheck',r.residualCheck, ...
    'quadratureCheck',r.quadratureCheck,'maximumRoofHeight_m',max(roof(:,3)), ...
    'totalDownwardForce_kN',-sum(s.F(3:3:end)), ...
    'maximumNodalForce_kN',max(abs(s.F(3:3:end))), ...
    'minimumAxialForce_kN',min(s.force),'maximumAxialForce_kN',max(s.force), ...
    'currentInitialBoundingBox_m',max(m.nodes,[],1)-min(m.nodes,[],1), ...
    'secondsWithDiagnostics',r.seconds, ...
    'diagnosticCallbackMayStop',false,'tolerancesChanged',false, ...
    'windDirection','upward','qD_kPa',4.5,'qW_kPa',.5, ...
    'innerObjective','U(u)-F_frozen^T*u; a different objective after each load update', ...
    'outerResidual','max(abs(Finternal-Frefreshed)) over free degrees of freedom');
gs_write_json(fullfile(out,'report.json'),report);
fprintf('FFT PASS: %d nodes, %d bars, %d supports; %d outer updates.\n', ...
    report.nodeCount,report.memberCount,report.supportCount,report.outerIterations);
fprintf('Residual %.12g <= %.12g kN; rise %.12g m.\n', ...
    r.residualCheck.freeForceResidual_kN,r.residualCheck.forceTolerance_kN,report.maximumRoofHeight_m);
fprintf('Loading: dead pressure 4.5 kPa downward; wind pressure 0.5 kPa upward.\n');
end
